/**
 * Writes (`--fix`) or verifies (`--check`) every self-describing facet's `selectors()`.
 *
 * The list is read off the facet's compiled ABI — every externally served function except the
 * unregistered helper views `getName()` and `selectors()`, the same set `Utils.getAllSelectors`
 * registers in a diamond — and rendered as a fixed-size array literal with one element per
 * selector, each under a comment naming its signature, in ascending selector order. A reviewer can
 * therefore check every value against the signature next to it, and `--check` holds the text to
 * the ABI. The encoding keeps the runtime code close to the packed form it replaced — the
 * AdminFacet sits near the EIP-170 limit: one `result[i] = …` per selector costs ~90 bytes each in
 * bounds checks, and a `bytes4` literal is left-aligned in its word, so each element would need a
 * 32-byte push. A `uint32` literal pushes in five bytes and converts once, in the copy loop.
 *
 * Reads `out/`, so run it after `forge build`.
 */
import { Command } from "commander";
import * as fs from "fs";
import * as path from "path";

const L1_CONTRACTS = path.resolve(__dirname, "..");

const FACETS: Array<{ source: string; contract: string }> = [
  { source: "contracts/state-transition/chain-deps/facets/Admin.sol", contract: "AdminFacet" },
  { source: "contracts/state-transition/chain-deps/facets/Getters.sol", contract: "GettersFacet" },
  { source: "contracts/state-transition/chain-deps/facets/Mailbox.sol", contract: "MailboxFacet" },
  { source: "contracts/state-transition/chain-deps/facets/Executor.sol", contract: "ExecutorFacet" },
  { source: "contracts/state-transition/chain-deps/facets/Migrator.sol", contract: "MigratorFacet" },
  { source: "contracts/state-transition/chain-deps/facets/Committer.sol", contract: "CommitterFacet" },
];

// Served by every facet, so registering them in a diamond would collide across facets.
const UNREGISTERED = new Set(["getName()", "selectors()"]);

const INDENT = "    ";

function methodIdentifiers(source: string, contract: string): Record<string, string> {
  const artifact = path.join(L1_CONTRACTS, "out", path.basename(source), `${contract}.json`);
  if (!fs.existsSync(artifact)) {
    throw new Error(`${artifact} not found: run \`forge build\` first`);
  }
  const ids = JSON.parse(fs.readFileSync(artifact, "utf-8")).methodIdentifiers;
  if (!ids) {
    throw new Error(`${artifact} has no methodIdentifiers`);
  }
  return ids;
}

/** The `selectors()` block, natspec included, exactly as `--fix` writes it. */
function render(ids: Record<string, string>): string {
  const rows = Object.entries(ids)
    .filter(([signature]) => !UNREGISTERED.has(signature))
    .map(([signature, selector]) => ({ signature, selector: selector.toLowerCase() }))
    .sort((a, b) => parseInt(a.selector, 16) - parseInt(b.selector, 16));
  return [
    "/// @inheritdoc ISelfDescribingFacet",
    "/// @dev GENERATED by `yarn l1 facet-selectors --fix` from this facet's ABI: every externally",
    "///      served function except the unregistered helper views `getName()` and `selectors()`",
    "///      (see `Utils.getAllSelectors`), in ascending selector order. Guarded against drift by",
    "///      FacetSelfDescription.t.sol and `yarn l1 facet-selectors --check`.",
    "function selectors() public pure returns (bytes4[] memory result) {",
    `${INDENT}uint32[${rows.length}] memory list = [`,
    ...rows.flatMap((row, i) => [
      `${INDENT}${INDENT}// ${row.signature}`,
      `${INDENT}${INDENT}uint32(0x${row.selector})${i === rows.length - 1 ? "" : ","}`,
    ]),
    `${INDENT}];`,
    `${INDENT}uint256 count = list.length;`,
    `${INDENT}result = new bytes4[](count);`,
    `${INDENT}for (uint256 i = 0; i < count; ++i) {`,
    `${INDENT}${INDENT}result[i] = bytes4(list[i]);`,
    `${INDENT}}`,
    "}",
  ]
    .map((line) => INDENT + line)
    .join("\n");
}

/** The span of the current block: its contiguous `///` natspec, through the function's closing brace. */
function locate(text: string, source: string): { start: number; end: number } {
  const fn = text.indexOf(`${INDENT}function selectors() `);
  if (fn === -1 || text.indexOf(`${INDENT}function selectors() `, fn + 1) !== -1) {
    throw new Error(`${source}: expected exactly one \`function selectors()\``);
  }
  let start = fn;
  for (;;) {
    const previousLineStart = text.lastIndexOf("\n", start - 2) + 1;
    if (!text.slice(previousLineStart, start).trimStart().startsWith("///")) {
      break;
    }
    start = previousLineStart;
  }
  let depth = 0;
  for (let i = text.indexOf("{", fn); i < text.length; ++i) {
    if (text[i] === "{") {
      ++depth;
    } else if (text[i] === "}" && --depth === 0) {
      return { start, end: i + 1 };
    }
  }
  throw new Error(`${source}: unbalanced braces after \`function selectors()\``);
}

function main() {
  const program = new Command();
  program
    .option("--fix", "rewrite every facet's selectors() from its compiled ABI")
    .option("--check", "fail if any facet's selectors() differs from what --fix writes")
    .parse(process.argv);
  const options = program.opts<{ fix?: boolean; check?: boolean }>();
  if (!options.fix === !options.check) {
    console.error("Pass exactly one of --fix or --check.");
    process.exit(1);
  }

  const stale: string[] = [];
  for (const { source, contract } of FACETS) {
    const file = path.join(L1_CONTRACTS, source);
    const text = fs.readFileSync(file, "utf-8");
    const { start, end } = locate(text, source);
    const expected = render(methodIdentifiers(source, contract));
    if (text.slice(start, end) === expected) {
      continue;
    }
    if (options.fix) {
      fs.writeFileSync(file, text.slice(0, start) + expected + text.slice(end));
      console.log(`${contract}: selectors() rewritten`);
    } else {
      stale.push(contract);
    }
  }
  if (stale.length !== 0) {
    console.error(`selectors() is stale in ${stale.join(", ")}: run \`yarn l1 facet-selectors --fix\``);
    process.exit(1);
  }
  console.log(options.fix ? "facet selectors written" : "facet selectors are current");
}

main();
